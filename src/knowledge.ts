const normalize = (value: string) =>
  value.normalize("NFKC").toLowerCase().replace(/\s+/g, " ").trim();
export function searchKnowledge(question: string, limit = 3): KnowledgeTopic[] {
  // Avoid mistaking the Korean question ending “무엇인가요” for authorization.
  const q = normalize(question).replace(
    /(?:무엇|뭐|뭔|것|건|뜻|차이)인가요?/g,
    "",
  );
  const hits: {
    topic: KnowledgeTopic;
    start: number;
    end: number;
    term: string;
  }[] = [];
  for (const topic of knowledgeTopics)
    for (const alias of topic.aliases) {
      const term = normalize(alias);
      const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const pattern = /[a-z0-9]/.test(term)
        ? `(?<![a-z0-9])${escaped}(?![a-z0-9])`
        : escaped;
      for (const match of q.matchAll(new RegExp(pattern, "gu")))
        hits.push({
          topic,
          start: match.index!,
          end: match.index! + term.length,
          term,
        });
    }
  const scores = new Map<KnowledgeTopic, number>();
  for (const hit of hits) {
    if (
      hits.some(
        (other) =>
          other.topic !== hit.topic &&
          other.start <= hit.start &&
          other.end >= hit.end &&
          other.term.length > hit.term.length,
      )
    )
      continue;
    scores.set(hit.topic, (scores.get(hit.topic) ?? 0) + hit.term.length);
  }
  return [...scores.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map(([topic]) => topic);
}

function plan(chapter: ChapterData, role: "red" | "blue"): RolePlan {
  const actions: Action[] = chapter.stages.flatMap((stage, i) => {
    const names =
      role === "red"
        ? [
            stage[1],
            `${stage[1]} · 영향 범위 확대 비교`,
            `${stage[1]} · 추가 근거 중심 비교`,
          ]
        : [stage[2], stage[3], stage[4]];
    return [...names, "확인 절차를 생략하고 빠르게 결정"].map(
      (name, tactic) => ({
        id: `step-${i}-${tactic}`,
        name,
        description:
          tactic === 3
            ? "고급 선택 · 확인 비용은 줄지만 오판·가용성 손실 위험이 큽니다."
            : role === "red"
              ? [
                  "좁은 범위의 비교로 신뢰 경계를 검토합니다.",
                  "더 넓은 비교로 증거를 얻지만 위험과 업무 영향이 큽니다.",
                  "추가 근거에 집중합니다. 보호 정책과의 충돌 여부를 살펴보세요.",
                ][tactic]
              : [
                  "접근·검증 정책으로 직접 대응합니다.",
                  "업무·출처 맥락을 재확인합니다.",
                  "영향 범위만 분리해 확산을 제한합니다.",
                ][tactic],
        effect: {},
        once: true,
        requires: i ? [`stage:${i}`] : [],
        excludes: [`stage:${i + 1}`],
        flags: [`stage:${i + 1}`],
        tactic,
        result: stage[5],
        ...(tactic === 3 ? { minDifficulty: "advanced" as const } : {}),
      }),
    );
  });
  return {
    objective:
      role === "red"
        ? "가상 신뢰 경계를 비교하고 방어 효과와 개선안을 증명하세요."
        : "공개된 공격 징후에 맞는 방어를 고르고 정상 업무를 지키세요.",
    initial: { ...initialStats },
    aiRules: { ...rules },
    actions,
    win: ["stage:5"],
    ai: "상황·위험도·직전 전술·난이도에 따라 대응합니다. 외부 API를 사용하지 않습니다.",
    feedback: chapter.summary,
  };
}
